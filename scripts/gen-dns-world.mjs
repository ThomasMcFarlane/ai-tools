import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { feature } from 'topojson-client';

const require = createRequire(import.meta.url);
const topology = JSON.parse(readFileSync(require.resolve('world-atlas/land-110m.json'), 'utf8'));
const land = feature(topology, topology.objects.land);
const width = 1000;
const height = 500;
const round = (n) => Math.round(n * 10) / 10;
const point = ([lon, lat]) => [
  round(((lon + 180) / 360) * width),
  round(((90 - lat) / 180) * height),
];

const rings = [];
for (const geometry of land.features ?? [land]) {
  const g = geometry.geometry ?? geometry;
  const polygons = g.type === 'Polygon' ? [g.coordinates] : g.coordinates;
  for (const polygon of polygons) {
    for (const ring of polygon) {
      if (ring.every(([, lat]) => lat > -60 || Math.abs(lat) > 90)) rings.push(ring);
    }
  }
}

const parts = rings.map((ring) => {
  let px = 0;
  let py = 0;
  const segments = ring.map((coord, index) => {
    const [x, y] = point(coord);
    if (index === 0) {
      px = x;
      py = y;
      return `M${x} ${y}`;
    }
    const jump = Math.abs(x - px) > width / 2;
    const dx = round(x - px);
    const dy = round(y - py);
    px = x;
    py = y;
    return jump ? `m${dx} ${dy}` : `l${dx} ${dy}`;
  });
  return `${segments.join('')}z`;
});

const out = [
  '// Generated by scripts/gen-dns-world.mjs from world-atlas land-110m. Do not edit.',
  `export const WORLD_WIDTH = ${width};`,
  `export const WORLD_HEIGHT = ${height};`,
  `export const WORLD_LAND_PATH =\n  '${parts.join('')}';`,
  '',
].join('\n');
writeFileSync(new URL('../tools/dns-checker/src/map/world.ts', import.meta.url), out);
